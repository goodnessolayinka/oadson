"""
api/chat_stream.py — OADSON V3 SSE Chat Streaming.

Wire contract is dictated by the existing frontend client (chat.html),
not invented here. The client's SSE parser recognizes exactly these
event types and field names — anything else is silently ignored:

    event: skill    data: {"name": <skill>, "args": {...}}
                    → skill is about to execute
    event: result   data: {"name": <skill>, "args": {...},
                            "output": {...} | null, "error": <str> | null}
                    → skill finished
    event: done     data: {"reply": <final text>, "model": <model_used>,
                            "pending_tool_call": {...} | null,
                            "contents_snapshot": [...] | null}
                    → terminal event carrying the final answer, or a
                      paused local-tool call for the client to execute
                      and resume (see api/chat.py's ChatResponse for the
                      matching non-streaming fields)
    event: error    data: {"message": <str>}
                    → terminal event on failure
    event: thinking data: {"text": <str>, "skill": null}
                    → short narration of what the model is about to do,
                      generated by a separate, cheaper Gemini call made
                      just before the real function-calling decision each
                      loop iteration (see AIOrchestrator._generate_thinking)
    event: status   data: {"status": <str>, "reason": <str> | null}
                    → OADSON V3 Intelligent Response State EDD. status is
                      one of "accepted" | "thinking" | "working_on_it".
                      "accepted" fires once, the moment the backend has
                      genuinely started this turn (forwarded from
                      Events.CHAT_STARTED — see core/event_bus.py) — this
                      is what the frontend's SENDING state waits for.
                      "working_on_it"/"thinking" are forwarded from
                      Events.RESPONSE_STATUS_CHANGED, emitted by
                      core/orchestrator.py around its provider-fallback and
                      streaming-fallback recovery paths (see that file's
                      RESPONSE_STATUS_CHANGED call sites). There is
                      deliberately no separate "background" status — the
                      frontend already infers that from the existing
                      `skill` event above, per the EDD's instruction not to
                      duplicate signals that already exist.

Every event carries only what the client actually reads — extra fields are
harmless (the client's JSON.parse + property access ignores anything
unused) but kept minimal here to match the contract exactly.
"""

import asyncio
import json
import os
import uuid
import logging

from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import StreamingResponse
from pydantic import BaseModel
from typing import Optional, List, Dict, Any

from dependency import get_current_user, get_orchestrator, get_db, get_event_bus
from core.event_bus import Events

logger = logging.getLogger("oadson.api.chat_stream")

router = APIRouter()

HEARTBEAT_SECONDS = 15


class ChatStreamRequest(BaseModel):
    message: str
    session_id: Optional[str] = None
    surface: Optional[str] = "web"
    local_execution: Optional[bool] = False
    context: Optional[str] = None
    # Sent by chat.html — not currently read by the orchestrator, accepted
    # here so the request body validates instead of 422ing.
    task_type: Optional[str] = None
    enable_reasoning: Optional[bool] = False
    # Lite mode = True: backend calls streamGenerateContent, emits TOKEN_STREAM per chunk.
    # Turbo mode = False: backend uses generateContent result directly, emits once on done.
    # Defaults True (Lite) so existing clients without this field get streaming.
    stream_tokens: Optional[bool] = True
    # File attachment fields chat.html sends for base64 archives / images.
    # If file_type is an image mime type, this now feeds real vision
    # support (orchestrator.run()'s image_data/image_mime) — previously
    # accepted but never actually used for anything.
    file_data: Optional[str] = None
    file_name: Optional[str] = None
    file_type: Optional[str] = None
    cloudinary_url: Optional[str] = None
    # Real text content of a non-image attachment (chat.html already
    # reads this client-side for PREVIEW_EXTS files) — see the
    # objective-building logic below for why this replaced the old
    # URL-note-only behavior.
    file_text: Optional[str] = None
    # Real multi-file support — previously chat.html collected every
    # attached file correctly but only ever sent the FIRST one
    # (filesToSend[0]); everything else silently never reached the
    # backend at all. Each item: {file_name, file_type, file_data
    # (base64, images/archives), file_text (text files), cloudinary_url}.
    # Kept the singular fields above for backward compatibility — a
    # request using only those still works exactly as before.
    attachments: Optional[List[Dict[str, Any]]] = None
    # FIX 2026-08-27 — PARITY WITH api/chat.py's ChatRequest: this field
    # was missing entirely from this streaming endpoint's request model.
    # A native-function-calling resume (terminal executes a local tool —
    # write_file, run_bash, create_file, etc via core/tool_loop.py's
    # LOCAL_TOOL_NAMES pause — then sends the result back to continue the
    # SAME turn) deliberately sends message="" and carries the actual
    # turn content here instead (see core/orchestrator.py's contents
    # override, right after the normal history-building block — same
    # mechanism api/chat.py already used correctly). Because this field
    # didn't exist on this model, FastAPI/Pydantic silently dropped it
    # from every request that included it (extra fields are ignored by
    # default, not rejected) — the backend then saw an empty message
    # with nothing to resume from, and the guard below correctly-by-its-
    # own-logic rejected it with a 400. Every multi-step tool chain
    # (anything needing 2+ sequential local tool calls in one turn) hit
    # this 400 on the SECOND tool call, every time, over the streaming
    # path specifically — non-streaming /chat already had this field and
    # worked correctly the whole time, which is why the same tool chains
    # worked fine through `oadson ask` (non-streaming) but not the
    # interactive REPL (streaming).
    resume_contents: Optional[list] = None
    # ADDED 2026-09-09 — PARITY WITH api/chat.py's ChatRequest.model.
    # Same contract: value must match an "id" from GET /models (see
    # api/models.py), ONLY honored for surface in ("web", "app", "pwa")
    # — enforced at the orchestrator.run() call below, not here, so a
    # client on any other surface sending this by mistake is silently
    # ignored rather than trusted. A miss (unknown id, unsupported for
    # this turn's tools, over quota) falls through to normal automatic
    # routing exactly as if this were never sent — see
    # core/provider_router.py's decide_preferred docstring.
    model: Optional[str] = None

    model_config = {
        "json_schema_extra": {
            "example": {
                "message": "Check my unread Gmail",
                "session_id": None,
                "surface": "web",
            }
        }
    }


def _sse(event: str, data: dict) -> str:
    return f"event: {event}\ndata: {json.dumps(data, default=str)}\n\n"


@router.post(
    "/chat/stream",
    summary="Send a message, stream live progress",
    description=(
        "Same request body as POST /chat, but returns text/event-stream "
        "instead of one JSON blob. Events: `skill` (about to run a tool), "
        "`result` (tool finished), `thinking` (optional narration, only if "
        "ENABLE_THINKING=true), `status` (accepted/thinking/working_on_it — "
        "see OADSON V3 Intelligent Response State EDD), `done` (final "
        "answer), `error`."
    ),
)
async def chat_stream(
    request: Request,
    body: ChatStreamRequest,
    user: dict = Depends(get_current_user),
    orchestrator=Depends(get_orchestrator),
    db=Depends(get_db),
    bus=Depends(get_event_bus),
):
    # FIX 2026-08-27 — mirrors api/chat.py's 2026-08-24 fix, ported here:
    # was unconditional, rejecting ANY empty message with a 400 —
    # including a native-function-calling resume request, which
    # deliberately sends message="" since the actual turn content lives
    # in resume_contents instead (see ChatStreamRequest's field comment
    # above, and core/orchestrator.py's contents override). Every resume
    # request over THIS streaming endpoint hit this 400, every time,
    # deterministically — not a network issue, despite genuinely
    # LOOKING like one from the terminal client (agent.py's own
    # CONTINUATION_RETRIES would retry the identical request 2 more
    # times, failing identically each time, since retrying doesn't
    # change a request the server was always going to reject on shape
    # alone). This is why a single local tool call worked fine (first
    # request of a turn always has a real message) but any SECOND
    # sequential tool call in the same turn failed 100% of the time —
    # that second request is exactly the resume shape this guard used to
    # reject outright.
    if not body.resume_contents and (not body.message or not body.message.strip()):
        raise HTTPException(400, "Message cannot be empty.")

    # See api/chat.py — same fire-and-forget queue nudge, same reasoning.
    from core.job_queue import kick_job_queue
    asyncio.create_task(kick_job_queue(db, orchestrator))

    session_id = body.session_id or str(uuid.uuid4())
    objective = body.message.strip()
    # SIZE CAP 2026-08-31: same fix as api/chat.py — see that file's
    # comment for the full reasoning. Kept identical (same constant
    # value) since a CLI client can hit either endpoint.
    SHELL_CONTEXT_MAX_CHARS = 30_000
    if body.context:
        shell_context = body.context
        if len(shell_context) > SHELL_CONTEXT_MAX_CHARS:
            shell_context = (
                shell_context[:SHELL_CONTEXT_MAX_CHARS]
                + f"\n...[truncated — shell context was {len(body.context)} chars, "
                f"capped at {SHELL_CONTEXT_MAX_CHARS}]"
            )
        objective = f"{objective}\n\n[Shell Context]\n{shell_context}"

    # Real multi-file support via the shared processor (core/
    # attachment_processor.py) — previously only a single file's data
    # ever reached here regardless of how many were attached, and text
    # files only ever got a Cloudinary URL note the model can't fetch
    # (which is why @document_reader correctly said "not found" while
    # the model sometimes went on to guess a plausible-sounding
    # description anyway). Falls back to building a single-item list
    # from the legacy fields if the client didn't send the new
    # `attachments` array, so older requests keep working unchanged.
    from core.attachment_processor import process_attachments

    attachments_in = body.attachments
    if not attachments_in and (body.file_data or body.file_text or body.cloudinary_url):
        attachments_in = [{
            "file_name": body.file_name,
            "file_type": body.file_type,
            "file_data": body.file_data,
            "file_text": body.file_text,
            "cloudinary_url": body.cloudinary_url,
        }]

    att_result = await process_attachments(str(user["_id"]), objective, attachments_in)
    objective = att_result["objective"]
    # REPO INDEX — an uploaded code archive is indexed for this session so
    # heavy turns can retrieve relevant files instead of re-reading everything.
    # Restore this user's active repo index (after a restart) before routing.
    from core import repo_index as _ri
    from bootstrap import get as _bget, has as _bhas
    _repo_db = _bget("db") if _bhas("db") else None
    _uid = str(user["_id"])
    # APPROVAL — only the user's own message "approve <code>" approves an action.
    from core import approvals as _approvals
    _code = _approvals.parse_approve(objective)
    if _code:
        _approvals.approve(_uid, _code)
    try:
        await _ri.resolve_user(_repo_db, _uid)
        _switched = await _ri.maybe_switch(_repo_db, _uid, objective)
        if _switched:
            import logging as _lg
            _lg.getLogger("oadson.chat_stream").info(f"active repo switched to {_switched}")
    except Exception as _e:
        import logging as _lg
        _lg.getLogger("oadson.chat_stream").warning(f"repo index restore skipped: {_e}")

    if att_result.get("archive_data"):
        # The archive is indexed on the worker. Render keeps only a pointer to the folder.
        from core import worker_client as _wc
        from core import workspace_pointer as _wp
        _first = (attachments_in or [{}])[0] if attachments_in else {}
        _url = _first.get("url") or _first.get("attachment_url") or ""
        _name = _first.get("filename") or _first.get("attachment_filename") or "upload.zip"
        _args = {"action": "index_archive", "name": _name}
        if _url:
            _args["archive_url"] = _url
        else:
            _args["archive_b64"] = att_result["archive_data"]
        try:
            _res = await _wc.try_remote("github", {"user_id": _uid, "args": _args}, wait_s=150)
            if _res and _res.get("status") == "success":
                await _wp.set_active(_uid, _res["folder"])
            else:
                import logging as _lg
                _lg.getLogger("oadson.chat_stream").warning(f"archive not indexed: {_res}")
        except Exception as _e:
            import logging as _lg
            _lg.getLogger("oadson.chat_stream").warning(f"archive index failed: {_e}")
    image_data = att_result["image_data"]
    image_mime = att_result["image_mime"]
    extra_images = att_result["extra_images"]
    extra_attachment_urls = att_result.get("extra_attachment_urls", [])

    # Durable attachment reference for persistence — see orchestrator.run()'s
    # attachment_url/type/filename docstring (it already fully supports
    # this — _persist_memory() writes it onto the saved message). This
    # extraction was missing here entirely: image_data/extra_images above
    # are deliberately ephemeral (used only for this one Gemini call,
    # never saved), and nothing else was ever passed through as the
    # durable reference — so a web-sent attachment had no way to survive
    # being displayed again after a reload, regardless of whether its
    # upload succeeded. Only the first attachment with a real URL is
    # used: _persist_memory() (and the web client reading it back via
    # GET /sessions/{id}) only support one attachment per message.
    attachment_url = None
    attachment_type = None
    attachment_filename = None
    for a in (attachments_in or []):
        url = a.get("cloudinary_url")
        if url:
            attachment_url = url
            attachment_type = a.get("file_type")
            attachment_filename = a.get("file_name")
            break

    # Archives don't go to Cloudinary — set a serve URL from sandbox path
    # so the frontend can display a download chip for the zip/archive.
    if not attachment_url and att_result.get("archive_name"):
        archive_name = att_result["archive_name"]
        backend_url = os.getenv("BACKEND_URL", os.getenv("RENDER_EXTERNAL_URL", "")).rstrip("/")
        attachment_url = f"{backend_url}/api/v3/files/serve/{session_id}/{archive_name}"
        attachment_type = "application/zip"
        attachment_filename = archive_name

    logger.info(f"[ATTACHMENT DEBUG] attachment_url={attachment_url!r} attachment_type={attachment_type!r} attachment_filename={attachment_filename!r}")

    queue: asyncio.Queue = asyncio.Queue()

    async def forward_token(event) -> None:
        if event.data.get("session_id") != session_id:
            return
        await queue.put(_sse("token", {
            "token": event.data.get("token", ""),
        }))

    async def forward_skill(event) -> None:
        if event.data.get("session_id") != session_id:
            return
        await queue.put(_sse("skill", {
            "name": event.data.get("skill"),
            "args": event.data.get("args") or {},
        }))

    async def forward_result(event) -> None:
        if event.data.get("session_id") != session_id:
            return
        await queue.put(_sse("result", {
            "name": event.data.get("skill"),
            "args": event.data.get("args") or {},
            "output": event.data.get("output"),
            "error": event.data.get("error"),
            "confidence": event.data.get("confidence"),
        }))

    # OADSON V3 Intelligent Response State EDD — see module docstring.
    # CHAT_STARTED already fires once, right as orchestrator.run() begins
    # (core/orchestrator.py) — reusing it as "accepted" rather than adding
    # a second backend-started signal that would say the same thing twice.
    async def forward_accepted(event) -> None:
        if event.data.get("session_id") != session_id:
            return
        await queue.put(_sse("status", {"status": "accepted", "reason": None}))

    async def forward_status(event) -> None:
        if event.data.get("session_id") != session_id:
            return
        await queue.put(_sse("status", {
            "status": event.data.get("status"),
            "reason": event.data.get("reason"),
        }))

    # TRACE MODE 2026-08-20: interstitial model text emitted alongside a
    # tool call, web/app + reasoning-on only (gated at the emission site
    # in orchestrator.py — this forwarder just relays whatever arrives).
    async def forward_trace_talk(event) -> None:
        if event.data.get("session_id") != session_id:
            # DEBUG LOGGING 2026-08-20 — a session_id mismatch here would
            # silently drop every talk event with zero trace in the logs
            # otherwise. Logged at warning (not the usual silent early
            # return every other forwarder in this file uses) specifically
            # because this is a NEW event type without a proven-safe track
            # record yet — if this line ever fires, that's the bug.
            logger.warning(
                f"TRACE talk event dropped — session mismatch: "
                f"event session={event.data.get('session_id')!r} "
                f"stream session={session_id!r}"
            )
            return
        logger.info(f"TRACE forwarding talk SSE, {len(event.data.get('text',''))} chars, session={session_id}")
        await queue.put(_sse("talk", {
            "text": event.data.get("text", ""),
        }))

    # ADDED 2026-09-19 — a stream that failed AFTER sending tokens is being
    # replaced by a fresh full answer. Tell the client to clear the partial
    # text first, or it renders the reply twice (partial + complete copy).
    async def forward_stream_reset(event) -> None:
        if event.data.get("session_id") != session_id:
            return
        logger.info(f"forwarding stream_reset SSE session={session_id} reason={event.data.get('reason')}")
        await queue.put(_sse("stream_reset", {"reason": event.data.get("reason", "")}))

    async def generator():
        # ENGINEER MODE — "/engineer on|off|status" and "report: ..." never reach the personal
        # assistant, and an Engineer chat stays in Engineer mode until switched off. Read-only.
        import datetime as _dt
        from core import engineer_mode as _em
        _cmd = _em.parse_command(objective)
        _engineer_on = _cmd is None and await _em.is_on(_repo_db, session_id)
        if _cmd is not None or _engineer_on:
            _img = None
            _first_att = (attachments_in or [None])[0] if attachments_in else None
            if isinstance(_first_att, dict):
                _img = _first_att.get("url") or _first_att.get("attachment_url")
            if _cmd is not None and _cmd[0] == "mode":
                _reply = await _em.apply_mode_command(_repo_db, session_id, _uid, _cmd[1])
                _img = None
            else:
                _report_text = _cmd[1] if _cmd is not None else objective
                if _cmd is not None:
                    await _em.save_report(_repo_db, _uid, session_id, _report_text, _img)
                _reply = (await _em.run_engineer(_uid, session_id, _report_text, _img))["reply"]
            yield _sse("talk", {"text": _reply})
            yield _sse("done", {"reply": _reply, "model": "engineer", "error": None,
                                "persisted_at": _dt.datetime.utcnow().isoformat()})
            await _em.persist_pair(_repo_db, session_id, _uid, objective, _reply, img_url=_img)
            return
        bus.subscribe(Events.TOKEN_STREAM, forward_token)
        bus.subscribe(Events.STREAM_RESET, forward_stream_reset)
        bus.subscribe(Events.TASK_STARTED, forward_skill)
        bus.subscribe(Events.TOOL_EXECUTED, forward_result)
        bus.subscribe(Events.CHAT_STARTED, forward_accepted)
        bus.subscribe(Events.RESPONSE_STATUS_CHANGED, forward_status)
        bus.subscribe(Events.TRACE_TALK, forward_trace_talk)

        run_task = asyncio.create_task(orchestrator.run(
            objective=objective,
            user=user,
            session_id=session_id,
            surface=body.surface or "web",
            local_execution=body.local_execution or False,
            image_data=image_data,
            image_mime=image_mime,
            extra_images=extra_images,
            enable_reasoning=body.enable_reasoning or False,
            stream_tokens=body.stream_tokens if body.stream_tokens is not None else True,
            attachment_url=attachment_url,
            attachment_type=attachment_type,
            attachment_filename=attachment_filename,
            extra_attachment_urls=extra_attachment_urls,
            # FIX 2026-08-27 — see ChatStreamRequest's resume_contents
            # field comment and the guard fix above for the full
            # rationale. Without this line, the field would validate
            # through FastAPI correctly and pass the (now-fixed) empty-
            # message guard, but still never actually reach the
            # orchestrator — core/orchestrator.py's contents override
            # only fires when THIS parameter is non-None, so the resume
            # would silently fall through to normal history-building
            # with an empty objective instead of resuming the paused
            # tool-call turn.
            resume_contents=body.resume_contents,
            # SURFACE GATE 2026-09-09 — same enforcement point and same
            # reasoning as api/chat.py's identical line; see
            # ChatStreamRequest.model's field comment above.
            preferred_model=body.model if (body.surface or "web") in ("web", "app", "pwa") else None,
        ))

        # STOP — register this turn so POST /chat/stop can cancel it.
        from core import run_control
        run_control.begin(session_id, run_task, str(user["_id"]))
        run_task.add_done_callback(lambda t, sid=session_id: run_control.end(sid, t))

        try:
            # BUG FIXED 2026-08-20 — the single biggest cause of the
            # reported "it reverts to a different/flattened answer after
            # being done" symptom, confirmed from production logs: hitting
            # Stop (frontend's abortCtrl.abort()) only tears down the
            # CLIENT's fetch connection — it was never communicated to the
            # backend at all. run_task above was created with
            # asyncio.create_task and then completely unlinked from
            # whether anyone was still listening: nothing here ever
            # called run_task.cancel(). So stopping a response and
            # immediately sending a new message didn't replace the first
            # request — it started a SECOND, fully independent orchestrator
            # run on the same session, while the first one kept executing
            # to completion in the background, unaware it had been
            # abandoned, right down to its own _persist_memory() call and
            # RESPONSE_READY emission. Two genuinely different assistant
            # messages (different models, different steps, one possibly
            # having hit its own streaming-fallback path) could land on
            # the same session within about a second of each other —
            # exactly what a matched pair of "Response ready" log lines a
            # second apart, for two different models, meant in practice.
            # Whichever one a later reload happened to fetch is what the
            # user saw — not the same response "losing" its formatting,
            # but possibly a different response entirely.
            #
            # Fix: poll request.is_disconnected() alongside the queue
            # wait (same timeout, no extra latency added to normal
            # streaming) and actually cancel run_task the moment the
            # client is gone, instead of letting it run to completion
            # orphaned.
            while not run_task.done():
                if await request.is_disconnected():
                    logger.info(f"Client disconnected mid-turn, cancelling run_task for session={session_id}")
                    run_task.cancel()
                    try:
                        await run_task
                    except asyncio.CancelledError:
                        pass
                    return
                try:
                    frame = await asyncio.wait_for(queue.get(), timeout=HEARTBEAT_SECONDS)
                    yield frame
                except asyncio.TimeoutError:
                    # Keep the connection alive through proxies/load
                    # balancers that drop idle SSE connections.
                    yield ": heartbeat\n\n"

            # Drain any events still sitting in the queue after the task
            # finished (small race between run_task completing and its
            # last emitted events landing in the queue).
            while not queue.empty():
                yield queue.get_nowait()

            try:
                result = run_task.result()
            except asyncio.CancelledError:
                # Stopped by the user. End the stream cleanly, not as an error.
                yield _sse("done", {"stopped": True, "session_id": session_id, "response": ""})
                return
            if "error" in result and not result.get("response"):
                yield _sse("error", {"message": result["error"]})
            else:
                # Was silently dropped here even after being available on
                # `result` — the branch above almost never fires (orchestrator
                # .run()'s exception handler always sets a non-empty
                # "response" alongside "error"), so this "done" event is the
                # only place a mid-flight error actually reaches the client.
                # Extra fields are harmless per this file's wire-contract
                # docstring — existing clients ignore fields they don't read.
                # DEBUG LOGGING 2026-09-10 — companion to orchestrator.py's
                # and tool_loop.py's matching TRACE lines. Confirms the
                # "done" event actually got yielded and what it carried —
                # without this, a silent gap between the last TRACE line
                # and a client-side timeout/404 was undiagnosable: no way
                # to tell whether the backend never reached this yield, or
                # reached it but the frame was dropped/never consumed.
                logger.info(f"TRACE yielding done — session={session_id} pending_tool_call={(result.get('pending_tool_call') or {}).get('name')}")
                yield _sse("done", {
                    "reply": result["response"],
                    "model": result.get("model_used", "unknown"),
                    "error": result.get("error"),
                    # TIMESTAMP FIX 2026-08-20 — see orchestrator.py's
                    # ctx["persisted_at"] comment. Was missing entirely
                    # before; chat.html's done handler used to fabricate
                    # its own timestamp from the client clock instead.
                    "persisted_at": result.get("persisted_at"),
                    # STREAMING PARITY FIX — api/chat.py's ChatResponse has
                    # declared pending_tool_call/contents_snapshot since the
                    # 2026-08-23 native function-calling migration (see that
                    # file's own field comment), but this "done" event never
                    # forwarded them, so a local-tool pause (terminal surface,
                    # core/tool_loop.py's LOCAL_TOOL_NAMES check) was
                    # observable over /chat but silently vanished over
                    # /chat/stream — the client would see reply="" with no
                    # pending call to act on, indistinguishable from a real
                    # empty answer. Same fields, same meaning, just also
                    # present on this path now.
                    "pending_tool_call": result.get("pending_tool_call"),
                    "contents_snapshot": result.get("contents_snapshot"),
                })

        except Exception as e:
            logger.error(f"chat_stream failed for session {session_id}: {e}", exc_info=True)
            yield _sse("error", {"message": str(e)})
        finally:
            bus.unsubscribe(Events.TOKEN_STREAM, forward_token)
            bus.unsubscribe(Events.STREAM_RESET, forward_stream_reset)
            bus.unsubscribe(Events.TASK_STARTED, forward_skill)
            bus.unsubscribe(Events.TOOL_EXECUTED, forward_result)
            bus.unsubscribe(Events.CHAT_STARTED, forward_accepted)
            bus.unsubscribe(Events.RESPONSE_STATUS_CHANGED, forward_status)
            bus.unsubscribe(Events.TRACE_TALK, forward_trace_talk)

    return StreamingResponse(
        generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            # Disable buffering on nginx-style reverse proxies (Railway's
            # edge included) so events flush immediately instead of
            # batching until the response closes.
            "X-Accel-Buffering": "no",
        },
    )


@router.post("/chat/stop", summary="Stop a running chat turn now")
async def stop_chat(body: dict, user: dict = Depends(get_current_user)):
    """
    The Stop button. Cancels this user's running turn on the server so no
    further model calls are made. Only the user who started a turn can stop it.
    """
    from core import run_control
    session_id = str((body or {}).get("session_id") or "")
    if not session_id:
        return {"status": "error", "reason": "session_id is required"}
    stopped = run_control.request_stop(session_id, str(user["_id"]))
    # STOP reaches the worker too: this user's unfinished remote jobs are cancelled.
    from core import worker_client as _wc
    try:
        remote_cancelled = await _wc.cancel_user_jobs(str(user["_id"]))
    except Exception:
        remote_cancelled = 0
    return {"status": "stopped" if stopped else "not_running", "session_id": session_id,
            "remote_jobs_cancelled": remote_cancelled}
